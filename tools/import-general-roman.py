#!/usr/bin/env python3
"""Import fixed General Roman Calendar facts/localizations from the pinned MIT Romcal source.
Usage: python3 tools/import-general-roman.py /path/to/romcal
No third-party code is executed. Movable/transfer/precedence rules remain native Kotlin.
"""
from pathlib import Path
import ast,json,re,subprocess,sys
source=Path(sys.argv[1]); pin='0671305334e0a5ae7eec8f50a46c7a21e3e40347'
assert subprocess.check_output(['git','rev-parse','HEAD'],cwd=source,text=True).strip()==pin
base=source/'rites/roman1969/src'
names={}
for lang in ['en','es','pt-br']:
 names[lang]={m[1]:ast.literal_eval(m[2]) for m in re.finditer(r'^\s*([a-z0-9_]+):\s*(\'(?:\\.|[^\'\\])*\'|"(?:\\.|[^"\\])*")',(base/f'locales/{lang}.ts').read_text(),re.M)}
rows=[]
for key,body in re.findall(r'^    ([a-z0-9_]+): \{\n(.*?)^    \},?',(base/'calendars/general-roman/index.ts').read_text(),re.M|re.S):
 date=re.search(r'dateDef:\s*\{\s*month:\s*(\d+),\s*date:\s*(\d+)',body)
 rank=re.search(r'precedence:\s*Precedences\.(\w+)',body)
 if not date:continue
 assert rank is not None
 precedence=rank[1]
 mapped={'GeneralMemorial_10':'MEMORIAL','OptionalMemorial_12':'OPTIONAL_MEMORIAL','GeneralFeast_7':'FEAST','GeneralLordFeast_5':'FEAST','GeneralSolemnity_3':'SOLEMNITY','ProperOfTimeSolemnity_2':'COMMEMORATION'}[precedence]
 color=re.search(r'colors:\s*Colors\.(\w+)',body)
 values=[json.dumps(names[lang][key],ensure_ascii=False).replace('$','\\$') for lang in ['es','en','pt-br']]
 internal={'visitation_of_mary':'visitation','dedication_of_the_lateran_basilica':'dedication_lateran'}.get(key,key)
 rows.append(f'        GeneralCelebration({date[1]}, {date[2]}, "{internal}", LocalizedText({", ".join(values)}), CelebrationRank.{mapped}, LiturgicalColor.{color[1].upper() if color else "WHITE"}, {str(precedence=="GeneralLordFeast_5").lower()}),')
assert len(rows)==219
out=Path('app/src/main/java/com/example/data/liturgy/GeneralRomanSanctoral.kt')
out.write_text('''package com.example.data.liturgy

import com.example.data.models.LocalizedText

/** Fixed dates/localizations adapted from Romcal under MIT; see assets/licenses/romcal-MIT.txt.
 * Source commit: '''+pin+'''. Generated by tools/import-general-roman.py.
 * Contemporary general calendar, not historical or a substitute for diocesan propers.
 */
internal data class GeneralCelebration(
    val month: Int, val day: Int, val key: String, val title: LocalizedText,
    val rank: CelebrationRank, val color: LiturgicalColor, val isLordFeast: Boolean
)

internal object GeneralRomanSanctoral {
    val fixed = listOf(
'''+ '\n'.join(rows)+'''
    )
}
''')
print('Imported',len(rows),'fixed celebrations in ES/EN/PT')
