In the Name of the Father, and of the Son, and of the Holy Spirit.

Amen.

Prayer of St Ambrose (Especially Before Holy Mass)

Lord Jesus Christ, I approach Thy banquet table in fear and trembling, for I am a sinner, and dare not rely on my own worth, but only on Thy goodness and mercy.

I am defiled by my many sins in body and soul, and by my unguarded thoughts and words.

Gracious God of majesty and awe, I seek Thy protection, I look for Thy healing.

Poor troubled sinner that I am, I appeal to Thee, the fountain of all mercy.

I cannot bear Thy judgment, but I trust in Thy salvation.

Lord, I show my wounds to Thee and uncover my shame before Thee.

I know my sins are many and great, and they fill me with fear, but I hope in Thy mercies, for they cannot be numbered.

Lord Jesus Christ, Eternal King, God and man, crucified for mankind, look upon me with mercy and hear my prayer, for I trust in Thee.

Have mercy on me, full of sorrow and sin, for the depth of Thy compassion never ends.

Praise to Thy saving sacrifice, offered on the wood of the cross for me and for all mankind.

Praise to the noble and precious Blood, flowing from the wounds of my crucified Lord Jesus Christ and washing away the sins of the whole world.

Remember, Lord, Thy creature, whom Thou hast redeemed with Thy blood; I repent my sins, and I long to put right what I have done.

Merciful Father, take away all my offenses and sins; purify me in body and soul, and make me worthy to taste the Holy of Holies.

May Thy Body and Blood, which I intend to receive, although I am unworthy, be for me the remission of my sins, the washing away of my guilt, the end of my evil thoughts, and the rebirth of my better instincts.

May it incite me to do the works pleasing to Thee, and a firm defense of body and soul against the wiles of my enemies. Amen.

(mention request here…)

Holy St. Ambrose, you are known as the Honey Tongued Doctor because of your ability to help others learn the truth of Christianity.

God blessed you with faith, understanding, and the great ability to preach the sweet words of the Gospel.

We invoke your powerful intercession, confident in the hope that you will hear our prayers and obtain for us abundant special graces from our heavenly Father.

Our Father

Hail Mary

