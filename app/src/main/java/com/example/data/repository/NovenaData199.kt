Que eu tenha sempre presente que nada me pode acontecer senão por particular disposição de um Deus que é infinitamente sábio e, por isso, sabe o que é melhor para o meu bem; infinitamente poderoso e, portanto, capaz de realizá-lo; e, acima de tudo, infinitamente misericordioso e amoroso, que deu a Sua vida pela minha redenção e continua a dar a cada dia novas provas do Seu amor e da Sua bondade.

