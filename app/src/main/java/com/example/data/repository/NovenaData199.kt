Ó terno Pai dos pobres, que, esgotados todos os outros recursos, vos oferecestes a vós mesmo para o seu alívio, alcançai-me aquele verdadeiro espírito de compaixão pelos membros sofredores de Jesus Cristo, que brilhou de modo tão notável em vossa santa vida.

Que eu, pela caridade para com aqueles que Jesus tanto ama, ajunte para mim tesouros no céu, onde agora gozais daquilo que os olhos não viram, nem os ouvidos ouviram, nem jamais passou pelo coração do homem, mas que Deus preparou para aqueles que O amam e que se mostram Seus discípulos pela observância do Seu divino preceito: amai-vos uns aos outros.

Louvo e agradeço a Deus pelo alto grau de santidade a que vos elevou e pelos privilégios especiais com que vos distinguiu.

Peço-vos, por aquela gratidão de que estareis penetrado por toda a eternidade para com o vosso divino Benfeitor, que imploreis para mim a graça de arrancar do meu coração tudo o que não é agradável aos Seus olhos, especialmente aquele mau hábito com que mais frequentemente O ofendo.

Alcançai-me igualmente, pela vossa poderosa intercessão, as graças que peço nesta Novena.

Ó gloriosa Mãe de Deus, Rainha do Santíssimo Rosário, vós que amastes Domingos com afeto de mãe e fostes por ele tão ternamente amada e honrada, olhai para mim, por amor dele, com olhos de compaixão e dignai-vos unir-vos a ele para apresentar estas súplicas ao vosso Bendito Jesus.

Desejo sinceramente, a partir deste momento, amá-Lo de todo o meu coração e servi-Lo com todas as minhas forças, e agora me coloco sob a vossa poderosa proteção, como meio seguro de obter todas as graças necessárias para servi-Lo fielmente aqui, a fim de que eu possa alegrar-me eternamente com Ele no além. Amém.

Em nome do Pai, do Filho e do Espírito Santo.

